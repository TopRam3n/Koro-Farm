from datetime import date, datetime
from decimal import Decimal
from enum import StrEnum
from uuid import UUID, uuid4

from sqlalchemy import Boolean, CheckConstraint, Date, DateTime, Enum, ForeignKey, Integer, Numeric, String, UniqueConstraint, func, true
from sqlalchemy.orm import Mapped, mapped_column

from src.backend.app.infrastructure.database.base import Base


class SupplyPlanStatus(StrEnum):
    FINALIZED = "FINALIZED"


class AllocationRole(StrEnum):
    COMMITTED = "COMMITTED"
    STANDBY = "STANDBY"


class AllocationStatus(StrEnum):
    PROPOSED = "PROPOSED"
    SOLICITED = "SOLICITED"
    ACCEPTED = "ACCEPTED"
    COMMITTED = "COMMITTED"
    STANDBY = "STANDBY"
    ACTIVATED = "ACTIVATED"
    LOST = "LOST"
    RELEASED = "RELEASED"
    CANCELLED = "CANCELLED"
    DECLINED = "DECLINED"
    WITHDRAWN = "WITHDRAWN"
    EXPIRED = "EXPIRED"


class ConsentStatus(StrEnum):
    """Whether the supplier's agreement behind an allocation is on record.

    RECORDED: a supplier_consents row records the acceptance or standby authorization.
    UNSUPPORTED_LEGACY: created before consent was recorded; its consent_evidence_id was generated by the
        planner and is not evidence of anything. Kept for history, never accepted as authorization.
    NONE: no agreement yet (proposed or solicited).
    """
    RECORDED = "RECORDED"
    UNSUPPORTED_LEGACY = "UNSUPPORTED_LEGACY"
    NONE = "NONE"


class ConsentType(StrEnum):
    COMMITMENT = "COMMITMENT"
    STANDBY_AUTHORIZATION = "STANDBY_AUTHORIZATION"


class ConsentDecision(StrEnum):
    ACCEPTED = "ACCEPTED"
    DECLINED = "DECLINED"


class ConsentChannel(StrEnum):
    """How the decision reached KoroFarm.

    FARMER_PORTAL: the farmer recorded it themselves while signed in (direct confirmation).
    COORDINATOR_RELAYED: a coordinator recorded the farmer's decision with an attestation method; this is a
        recorded decision but not independent farmer confirmation.
    SYNTHETIC_FIXTURE: written by the demo seed for synthetic demo data only.
    """
    FARMER_PORTAL = "FARMER_PORTAL"
    COORDINATOR_RELAYED = "COORDINATOR_RELAYED"
    SYNTHETIC_FIXTURE = "SYNTHETIC_FIXTURE"


class SupplyPlan(Base):
    __tablename__ = "supply_plans"
    __table_args__ = (
        CheckConstraint("required_quantity_kg > 0", name="ck_plan_required_positive"),
        CheckConstraint("committed_quantity_kg >= 0", name="ck_plan_committed_non_negative"),
        CheckConstraint("standby_quantity_kg >= 0", name="ck_plan_standby_non_negative"),
        CheckConstraint("unfilled_quantity_kg >= 0", name="ck_plan_unfilled_non_negative"),
        CheckConstraint("plan_version > 0", name="ck_plan_version_positive"),
        UniqueConstraint("requirement_id", "plan_version", name="uq_supply_plan_requirement_version"),
    )

    id: Mapped[UUID] = mapped_column(primary_key=True, default=uuid4)
    requirement_id: Mapped[UUID] = mapped_column(ForeignKey("requirements.id"), nullable=False, index=True)
    plan_version: Mapped[int] = mapped_column(Integer, nullable=False)
    planner_version: Mapped[str] = mapped_column(String(50), nullable=False)
    status: Mapped[SupplyPlanStatus] = mapped_column(Enum(SupplyPlanStatus, native_enum=False), nullable=False)
    required_quantity_kg: Mapped[Decimal] = mapped_column(Numeric(12, 3), nullable=False)
    committed_quantity_kg: Mapped[Decimal] = mapped_column(Numeric(12, 3), nullable=False)
    standby_quantity_kg: Mapped[Decimal] = mapped_column(Numeric(12, 3), nullable=False)
    unfilled_quantity_kg: Mapped[Decimal] = mapped_column(Numeric(12, 3), nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), nullable=False)


class SupplyAllocation(Base):
    __tablename__ = "supply_allocations"
    __table_args__ = (CheckConstraint("quantity_kg > 0", name="ck_allocation_quantity_positive"),)

    id: Mapped[UUID] = mapped_column(primary_key=True, default=uuid4)
    requirement_id: Mapped[UUID] = mapped_column(ForeignKey("requirements.id"), nullable=False, index=True)
    supply_plan_id: Mapped[UUID] = mapped_column(ForeignKey("supply_plans.id"), nullable=False, index=True)
    production_lot_id: Mapped[UUID] = mapped_column(ForeignKey("production_lots.id"), nullable=False, index=True)
    role: Mapped[AllocationRole] = mapped_column(Enum(AllocationRole, native_enum=False), nullable=False)
    status: Mapped[AllocationStatus] = mapped_column(Enum(AllocationStatus, native_enum=False, length=20), nullable=False)
    quantity_kg: Mapped[Decimal] = mapped_column(Numeric(12, 3), nullable=False)
    # Points at supplier_consents.id when consent_status is RECORDED. Legacy values are planner-generated ids.
    consent_evidence_id: Mapped[UUID | None] = mapped_column(nullable=True)
    consent_status: Mapped[ConsentStatus] = mapped_column(Enum(ConsentStatus, native_enum=False, length=30), nullable=False,
                                                          default=ConsentStatus.NONE, server_default=ConsentStatus.NONE.value)
    # True when quantity_kg is counted in production_lots.reserved_quantity_kg for this allocation.
    holds_reservation: Mapped[bool] = mapped_column(Boolean, nullable=False, default=True, server_default=true())
    activation_conditions: Mapped[str | None] = mapped_column(String(1000), nullable=True)
    authorization_valid_until: Mapped[date | None] = mapped_column(Date, nullable=True)
    solicited_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    responded_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    response_due_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    reminder_sent_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    activated_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    lost_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    plan_version: Mapped[int] = mapped_column(Integer, nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), nullable=False)


class SupplierConsent(Base):
    """An immutable record of a supplier's decision on a commitment or standby authorization."""
    __tablename__ = "supplier_consents"
    __table_args__ = (CheckConstraint("quantity_kg > 0", name="ck_consent_quantity_positive"),)

    id: Mapped[UUID] = mapped_column(primary_key=True, default=uuid4)
    organization_id: Mapped[UUID] = mapped_column(ForeignKey("organizations.id"), nullable=False, index=True)
    allocation_id: Mapped[UUID] = mapped_column(ForeignKey("supply_allocations.id"), nullable=False, index=True)
    farmer_id: Mapped[UUID] = mapped_column(ForeignKey("farmers.id"), nullable=False, index=True)
    production_lot_id: Mapped[UUID] = mapped_column(ForeignKey("production_lots.id"), nullable=False)
    consent_type: Mapped[ConsentType] = mapped_column(Enum(ConsentType, native_enum=False, length=30), nullable=False)
    decision: Mapped[ConsentDecision] = mapped_column(Enum(ConsentDecision, native_enum=False, length=20), nullable=False)
    channel: Mapped[ConsentChannel] = mapped_column(Enum(ConsentChannel, native_enum=False, length=30), nullable=False)
    quantity_kg: Mapped[Decimal] = mapped_column(Numeric(12, 3), nullable=False)
    attestation_method: Mapped[str] = mapped_column(String(100), nullable=False)
    evidence_reference: Mapped[str | None] = mapped_column(String(500), nullable=True)
    activation_conditions: Mapped[str | None] = mapped_column(String(1000), nullable=True)
    valid_until: Mapped[date | None] = mapped_column(Date, nullable=True)
    note: Mapped[str | None] = mapped_column(String(1000), nullable=True)
    recorded_by_user_id: Mapped[UUID | None] = mapped_column(nullable=True)
    recorded_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), nullable=False)
